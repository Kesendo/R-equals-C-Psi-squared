/// <summary>The free-fermion floor of the number-changing blocks, read block by block. Under the
/// uniform open XY chain with uniform Z-dephasing γ₀, <c>docs/proofs/PROOF_CHAIN_GAP_DOMINANCE.md</c>
/// §2-§3 builds the Jordan-Wigner family c_k^(†)·f(N_tot) of modes at exactly Re λ = −2γ₀. This witness reads that family inside each (n, n+1) popcount coherence
/// block, the block family F86 works in, built with F86's own <see cref="CoherenceBlock"/> and
/// <see cref="BlockLDecomposition"/>: f = P_{n+1} gives c_k·P_{n+1} = P_n·c_k·P_{n+1}, N modes per
/// block, at every chromaticity c. That holds on the open chain: on the ring the Δn = 1 floor is the
/// four outer blocks' alone at N = 4..8 (<c>PROOF_RING_GAP_DOMINANCE</c>). The family is the spectator
/// map's image of the (0,1) block, Wⁿ(P_0·c_j) = (−1)ⁿ·n!·P_n·c_j·P_{n+1} with W(ρ) = Σ_l c_l†ρc_l, and
/// <c>docs/proofs/PROOF_CODIM1_BY_ADDITIVITY.md</c> Theorem B (W intertwines L at any profile) is why
/// it is invariant under L, L† and every bond.
///
/// <para>The count stands on two exact routes and is read by a third. (1) A lower bound in
/// integers: the N vectors u_j = P_n·c_j·P_{n+1} (entries ±1, the Jordan-Wigner sign) have
/// disjoint supports on HD = 1 cells, and the integer hopping matrix K (L = D + iJ·K) maps their
/// span onto itself as ± the chain's adjacency matrix. So an N-dimensional K-invariant subspace
/// sits where D = −2γ₀, and L acts on it as −2γ₀ + iJ·(±A). (2) An upper bound mod p: the
/// largest K-invariant subspace inside the HD = 1 cells has dimension M − rank of the Krylov row
/// space generated by the unit rows of the HD ≠ 1 cells under K, and a rank over GF(p) can only
/// undercount. Every floor eigenvector lies in that subspace (Absorption: Re λ = −2γ₀⟨HD⟩ forces
/// HD = 1 support, and an eigenvector's K-image stays there), and K is symmetric, so its
/// dimension IS the floor eigenspace's. Equal bounds certify the count. (3) The block's full
/// spectrum (zgeev, left and right vectors) counts the modes at −2γ₀ against the rounding law
/// of a well-conditioned eigenvalue: the family is invariant under L and L† alike, so its left
/// and right eigenvectors coincide and its condition number is 1.</para>
///
/// <para>The Dicke probe (<see cref="DickeBlockProbe"/>, uniform over the block) reads a floor
/// mode through its biorthogonal overlap, which is the plain sum of the mode's entries. The exact
/// route: s_j = Σ entries of u_j is an integer, and s obeys s_{N−1−j} = ε·s_j under the chain
/// reflection (ε = (−1)^n, the sign the Jordan-Wigner string picks up), while the single-particle
/// vector φ_k has parity (−1)^(k+1). The mode's parity under the chain reflection of the coherence,
/// site j ↔ N−1−j on both of its sides, is the product of the two; an odd mode (φ_k parity differing
/// from ε) is silent to the probe, exactly, and the even ones read nonzero in every block the tests
/// check. In the (1,2) block the visible modes are the even k, the k-labels of F89's F_a set
/// (<c>F89PathKAtLockMechanismClaim.SeAntiBlochOrbit</c>, named there by φ_k's own parity); the
/// others sit on the floor all the same, silent to the probe by that parity alone.</para>
///
/// <para>What the floor is for the other readings: the global slowest rate of the number-changing
/// channel (<c>PostEpFlowField.IsInSterileZone</c>) reads this layer, which is Q-flat at uniform γ
/// in every block. The family's span is invariant under L and L† alike, so it splits off orthogonally
/// and no exceptional point of a block involves a mode of the family
/// (<see cref="FermionFloorBlockReading.NextRateAboveFloor"/> is the first rate off the floor). How much of
/// F86's K the floor carries, and how much the interference between floor and rest, is read by
/// <see cref="FloorSplitWitness"/> (<c>inspect --root floorsplit</c>).</para></summary>
public sealed class FreeFermionFloorWitness : IInspectable
{
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    public const int DefaultN = 5;
    public const double DefaultQ = 2.0;
    public const double DefaultGammaZero = 0.05;
    public const int MaxN = 7;

    /// <summary>Two primes below 2³⁰, so a product of two residues fits a long.</summary>
    private static readonly long[] Primes = { 1_000_000_007L, 998_244_353L };

    public int N { get; }
    /// <summary>Q = J/γ₀ with H = (J/2)·Σ(XX+YY), the F86 convention.</summary>
    public double Q { get; }
    public double GammaZero { get; }
    public double J => Q * GammaZero;
    public IReadOnlyList<FermionFloorBlockReading> Blocks { get; }

    public FreeFermionFloorWitness(int n = DefaultN, double q = DefaultQ, double gammaZero = DefaultGammaZero)
    {
        if (n < 2 || n > MaxN)
            throw new ArgumentOutOfRangeException(nameof(n), n, $"N must be in [2, {MaxN}].");
        if (!(q > 0) || double.IsInfinity(q))
            throw new ArgumentOutOfRangeException(nameof(q), q, "Q must be positive and finite.");
        if (!(gammaZero > 0) || double.IsInfinity(gammaZero))
            throw new ArgumentOutOfRangeException(nameof(gammaZero), gammaZero, "γ₀ must be positive and finite.");
        N = n;
        Q = q;
        GammaZero = gammaZero;
        var blocks = new List<FermionFloorBlockReading>(n);
        for (int lower = 0; lower < n; lower++)
            blocks.Add(ReadBlock(new CoherenceBlock(n, lower, gammaZero)));
        Blocks = blocks;
    }

    /// <summary>True when every block's integer lower bound meets its mod-p upper bound at N.</summary>
    public bool AllCertified => Blocks.All(b => b.FloorCertified);

    private FermionFloorBlockReading ReadBlock(CoherenceBlock block)
    {
        var basis = block.Basis;
        int m = basis.MTotal;
        int lower = basis.LowerPopcount;

        var hd = new int[m];
        foreach (long p in basis.StatesP)
            foreach (long q in basis.StatesQ)
                hd[basis.FlatIndex(p, q)] = BitOperations.PopCount((ulong)(p ^ q));

        var kNeighbours = IntegerHopping(block, m);

        // ---- route 1: the Jordan-Wigner family in integers ----
        var family = JordanWignerFamily(basis);
        bool onHd1 = family.All(u => u.Keys.All(c => hd[c] == 1));

        var t = new long[N, N];
        bool closed = true;
        for (int j = 0; j < N && closed; j++)
        {
            var image = new Dictionary<int, long>();
            foreach (var (cell, val) in family[j])
                foreach (var (target, kv) in kNeighbours[cell])
                    image[target] = image.GetValueOrDefault(target) + kv * val;
            foreach (var key in image.Where(e => e.Value == 0).Select(e => e.Key).ToList()) image.Remove(key);
            var owner = new Dictionary<int, int>();
            for (int jj = 0; jj < N; jj++) foreach (int c in family[jj].Keys) owner[c] = jj;
            // the supports are disjoint, so the coefficient on u_jj is read off one cell and checked on all
            foreach (var (cell, val) in image)
            {
                if (!owner.TryGetValue(cell, out int jj)) { closed = false; break; }
                long coef = val * family[jj][cell];
                if (t[jj, j] == 0) t[jj, j] = coef;
                else if (t[jj, j] != coef) { closed = false; break; }
            }
            if (!closed) break;
            for (int jj = 0; jj < N && closed; jj++)
                if (t[jj, j] != 0)
                    foreach (var (c, v) in family[jj])
                        if (image.GetValueOrDefault(c) != t[jj, j] * v) { closed = false; break; }
        }
        int sigma = closed && N > 1 ? (int)t[1, 0] : 1;
        bool isAdjacency = closed && (sigma == 1 || sigma == -1);
        for (int a = 0; a < N && isAdjacency; a++)
            for (int b = 0; b < N; b++)
                if (t[a, b] != (Math.Abs(a - b) == 1 ? sigma : 0)) { isAdjacency = false; break; }

        // ---- route 2: the largest K-invariant subspace inside the HD = 1 cells, mod p ----
        int upper = int.MaxValue;
        foreach (long prime in Primes)
            upper = Math.Min(upper, m - KrylovRowRankModP(hd, kNeighbours, m, prime));

        bool certified = onHd1 && closed && isAdjacency && upper == N;

        // ---- route 3: the block's spectrum, left and right ----
        Complex[] raw = BlockLDecomposition.BuildUniformLColumnMajorRaw(block, J);
        double frob = Math.Sqrt(raw.Sum(z => z.Real * z.Real + z.Imaginary * z.Imaginary));
        // the rounding scale of a condition-1 eigenvalue: ε_mach·‖L‖₂ ≤ ε_mach·‖L‖_F, with headroom 64
        double roundingUnit = 64.0 * Math.Pow(2, -52) * frob;
        var (values, left, right) = MklDirect.EigenvaluesLeftRightDirectRaw(raw, m);

        double floorRe = -2.0 * GammaZero;
        var predictedFreq = new double[N + 1];
        for (int k = 1; k <= N; k++) predictedFreq[k] = sigma * J * 2.0 * Math.Cos(Math.PI * k / (N + 1));

        // the probe is uniform: every entry is the same constant
        Complex probe = DickeBlockProbe.Build(block)[0];
        double probeNorm = probe.Magnitude * Math.Sqrt(m);
        // a dark overlap is a sum of rounding errors over m unit-vector entries; 1e6·ε_mach·‖probe‖ is far above it
        double darkCut = 1e6 * Math.Pow(2, -52) * probeNorm;

        int floorCount = 0;
        double maxFreqError = 0.0;
        double nextRate = double.NaN;
        var assigned = new HashSet<int>();
        var visible = new List<int>();
        var dark = new List<int>();
        double maxDark = 0.0, minVisible = double.PositiveInfinity;
        for (int i = 0; i < m; i++)
        {
            Complex lam = values[i];
            if (Math.Abs(lam.Real - floorRe) > roundingUnit)
            {
                double rate = -lam.Real / GammaZero;
                if (double.IsNaN(nextRate) || rate < nextRate) nextRate = rate;
                continue;
            }
            floorCount++;
            int kBest = 1;
            for (int k = 2; k <= N; k++)
                if (Math.Abs(lam.Imaginary - predictedFreq[k]) < Math.Abs(lam.Imaginary - predictedFreq[kBest])) kBest = k;
            if (!assigned.Add(kBest))
                throw new InvalidOperationException(
                    $"N={N} n={lower}: two floor modes read the same single-particle index k={kBest}.");
            maxFreqError = Math.Max(maxFreqError, Math.Abs(lam.Imaginary - predictedFreq[kBest]) / roundingUnit);

            long col = (long)i * m;
            Complex vlSum = Complex.Zero, vlHvr = Complex.Zero;
            for (int r = 0; r < m; r++)
            {
                Complex vl = left[col + r];
                vlSum += vl;
                vlHvr += Complex.Conjugate(vl) * right[col + r];
            }
            double c0 = (Complex.Conjugate(vlSum) * probe / vlHvr).Magnitude;
            if (c0 <= darkCut) { dark.Add(kBest); maxDark = Math.Max(maxDark, c0 * c0); }
            else { visible.Add(kBest); minVisible = Math.Min(minVisible, c0 * c0); }
        }

        // ---- the exact parity route to the dark set ----
        var s = new long[N];
        for (int j = 0; j < N; j++) s[j] = family[j].Values.Sum();
        bool allZero = s.All(x => x == 0);
        int eps = 0;
        bool reflectionExact;
        if (allZero) { reflectionExact = true; }
        else
        {
            int jRef = Array.FindIndex(s, x => x != 0);
            long mirror = s[N - 1 - jRef];
            eps = mirror == s[jRef] ? 1 : mirror == -s[jRef] ? -1 : 0;
            reflectionExact = eps != 0 && Enumerable.Range(0, N).All(j => s[N - 1 - j] == eps * s[j]);
        }
        var predictedDark = new List<int>();
        for (int k = 1; k <= N; k++)
        {
            int parity = (k % 2 == 1) ? 1 : -1;  // φ_k(N−1−j) = (−1)^(k+1)·φ_k(j)
            if (allZero || !reflectionExact || parity != eps) predictedDark.Add(k);
        }

        return new FermionFloorBlockReading(
            LowerPopcount: lower,
            Chromaticity: block.C,
            BlockDimension: m,
            Hd1Cells: hd.Count(h => h == 1),
            FamilyOnHd1Cells: onHd1,
            FamilyClosedUnderHopping: closed,
            HoppingIsChainAdjacency: isAdjacency,
            HoppingSign: sigma,
            FloorUpperBoundModP: upper,
            FloorCertified: certified,
            EigensolverFloorCount: floorCount,
            MaxFloorFrequencyErrorOverRounding: maxFreqError,
            NextRateAboveFloor: nextRate,
            DickeVisibleK: visible.OrderBy(k => k).ToList(),
            DickeDarkK: dark.OrderBy(k => k).ToList(),
            PredictedDarkK: predictedDark,
            ReflectionRelationExact: reflectionExact,
            ReflectionSign: eps,
            MaxDarkOverlapSquared: maxDark,
            MinVisibleOverlapSquared: minVisible);
    }

    /// <summary>The Jordan-Wigner family of the (n, n+1) block, u_j = P_n·c_j·P_(n+1) for j = 0..N−1:
    /// cell (p, q) with p = q minus site j carries the sign (−1)^(occupied sites before j), all other
    /// cells 0. Shared by every witness that reads this floor, so the construction has one copy.</summary>
    internal static Dictionary<int, int>[] JordanWignerFamily(BlockBasis basis)
    {
        int n = basis.N;
        var family = new Dictionary<int, int>[n];   // u_j: cell → ±1
        for (int j = 0; j < n; j++) family[j] = new Dictionary<int, int>();
        long fullMask = (1L << n) - 1;
        foreach (long q in basis.StatesQ)
            for (int j = 0; j < n; j++)
            {
                long bit = 1L << (n - 1 - j);              // big-endian: site 0 = MSB
                if ((q & bit) == 0) continue;
                long before = fullMask & ~((1L << (n - j)) - 1); // sites 0..j−1
                int sign = (BitOperations.PopCount((ulong)(q & before)) & 1) == 0 ? 1 : -1;
                family[j][basis.FlatIndex(q ^ bit, q)] = sign;
            }
        return family;
    }

    /// <summary>The integer hopping matrix K of the block, L = D + iJ·K, read off the block
    /// Liouvillian at J = 1 (its off-diagonal entries are exactly ±i, one flip per entry) and
    /// checked to be integer and symmetric. Returned as neighbour lists.</summary>
    private static List<(int Target, long Value)>[] IntegerHopping(CoherenceBlock block, int m)
    {
        Complex[] unit = BlockLDecomposition.BuildUniformLColumnMajorRaw(block, 1.0);
        var neighbours = new List<(int Target, long Value)>[m];
        for (int c = 0; c < m; c++) neighbours[c] = new List<(int, long)>();
        for (int col = 0; col < m; col++)
            for (int row = 0; row < m; row++)
            {
                if (row == col) continue;
                Complex z = unit[(long)col * m + row];
                if (z == Complex.Zero) continue;
                // K = −i·L_offdiag
                double kr = z.Imaginary, ki = -z.Real;
                long kv = (long)Math.Round(kr);
                if (ki != 0.0 || kr != kv)
                    throw new InvalidOperationException($"hopping entry ({row},{col}) = {z} is not i times an integer.");
                // (rK)_row-convention: neighbours[col] lists the rows K[row, col] ≠ 0, i.e. K·e_col
                neighbours[col].Add((row, kv));
            }
        for (int a = 0; a < m; a++)
            foreach (var (b, v) in neighbours[a])
                if (!neighbours[b].Contains((a, v)))
                    throw new InvalidOperationException($"hopping matrix not symmetric at ({a},{b}).");
        return neighbours;
    }

    /// <summary>Rank over GF(p) of the row space generated by the unit rows of the HD ≠ 1 cells
    /// under right multiplication by K (K symmetric, so r·K = (K·r)ᵀ). M minus this rank is the
    /// largest K-invariant subspace inside the HD = 1 cells, mod p an upper bound.</summary>
    private static int KrylovRowRankModP(int[] hd, List<(int Target, long Value)>[] k, int m, long p)
    {
        var basis = new List<(int Pivot, long[] Row)>();
        var queue = new Queue<long[]>();
        for (int c = 0; c < m; c++)
            if (hd[c] != 1) { var e = new long[m]; e[c] = 1; queue.Enqueue(e); }
        while (queue.Count > 0)
        {
            long[] v = queue.Dequeue();
            foreach (var (pivot, row) in basis)
            {
                if (v[pivot] == 0) continue;
                long f = v[pivot];
                for (int x = 0; x < m; x++)
                    if (row[x] != 0) v[x] = Mod(v[x] - f * row[x], p);
            }
            int lead = Array.FindIndex(v, x => x != 0);
            if (lead < 0) continue;
            long inv = ModPow(v[lead], p - 2, p);
            for (int x = 0; x < m; x++) if (v[x] != 0) v[x] = v[x] * inv % p;
            basis.Add((lead, v));
            var next = new long[m];
            for (int c = 0; c < m; c++)
                if (v[c] != 0)
                    foreach (var (target, kv) in k[c])
                        next[target] = Mod(next[target] + v[c] * Mod(kv, p), p);
            queue.Enqueue(next);
        }
        return basis.Count;
    }

    private static long Mod(long v, long p) { long r = v % p; return r < 0 ? r + p : r; }

    private static long ModPow(long b, long e, long p)
    {
        long r = 1; b = Mod(b, p);
        while (e > 0)
        {
            if ((e & 1) == 1) r = r * b % p;
            b = b * b % p;
            e >>= 1;
        }
        return r;
    }

    // ---- Object Manager ----
    public string DisplayName =>
        $"FreeFermionFloorWitness (N={N}, Q={Q.ToString("0.###", Inv)}, γ₀={GammaZero.ToString("0.###", Inv)})";

    public string Summary =>
        $"the Jordan-Wigner floor of the number-changing (n, n+1) blocks: " +
        $"{Blocks.Count(b => b.FloorCertified)}/{Blocks.Count} blocks certified at exactly N = {N} modes at Re λ = −2γ₀";

    public IEnumerable<IInspectable> Children
    {
        get
        {
            yield return new InspectableNode("the gate (integer lower bound meets the mod-p upper bound)",
                summary: AllCertified
                    ? $"certified: every (n, n+1) block holds exactly N = {N} floor modes, P_n·c_k·P_(n+1), k = 1..{N}, " +
                      "at every chromaticity; the spectrum (zgeev) counts the same"
                    : "NOT certified: " + string.Join("; ", Blocks.Where(b => !b.FloorCertified)
                        .Select(b => $"n={b.LowerPopcount}: upper bound {b.FloorUpperBoundModP}")));
            foreach (var b in Blocks)
            {
                string next = double.IsNaN(b.NextRateAboveFloor)
                    ? "the family is the whole block (pinned, F153)"
                    : $"first rate above the floor {b.NextRateAboveFloor.ToString("0.0000", Inv)} γ₀ (F86's EP lives up there)";
                yield return new InspectableNode(
                    $"({b.LowerPopcount}, {b.LowerPopcount + 1}) block, c = {b.Chromaticity}",
                    summary: $"dim {b.BlockDimension}; floor {b.EigensolverFloorCount} modes (exact bound {b.FloorUpperBoundModP}); " +
                             $"{next}; Dicke sees k ∈ {{{string.Join(",", b.DickeVisibleK)}}}, silent k ∈ {{{string.Join(",", b.DickeDarkK)}}} " +
                             $"(mirror sign ε = {b.ReflectionSign})");
            }
        }
    }

    public InspectablePayload Payload => InspectablePayload.Empty;
}

/// <summary>One (n, n+1) block's floor reading. <paramref name="FloorCertified"/>: the integer
/// family (on HD = 1 cells, closed under hopping as ± the chain adjacency) meets the mod-p upper
/// bound at N. <paramref name="MaxFloorFrequencyErrorOverRounding"/>: the floor frequencies against
/// J·σ·2cos(πk/(N+1)), in units of the rounding scale 64·ε_mach·‖L‖_F.
/// <paramref name="NextRateAboveFloor"/>: −Re λ/γ₀ of the slowest mode not on the floor, NaN when
/// the family is the whole block. <paramref name="PredictedDarkK"/>: the exact parity route
/// (s_{N−1−j} = ε·s_j against φ_k's parity (−1)^(k+1)); <paramref name="DickeDarkK"/> and
/// <paramref name="DickeVisibleK"/>: the eigensolver's biorthogonal Dicke overlap, dark when it is
/// at rounding scale.</summary>
public sealed record FermionFloorBlockReading(
    int LowerPopcount,
    int Chromaticity,
    int BlockDimension,
    int Hd1Cells,
    bool FamilyOnHd1Cells,
    bool FamilyClosedUnderHopping,
    bool HoppingIsChainAdjacency,
    int HoppingSign,
    int FloorUpperBoundModP,
    bool FloorCertified,
    int EigensolverFloorCount,
    double MaxFloorFrequencyErrorOverRounding,
    double NextRateAboveFloor,
    IReadOnlyList<int> DickeVisibleK,
    IReadOnlyList<int> DickeDarkK,
    IReadOnlyList<int> PredictedDarkK,
    bool ReflectionRelationExact,
    int ReflectionSign,
    double MaxDarkOverlapSquared,
    double MinVisibleOverlapSquared);
